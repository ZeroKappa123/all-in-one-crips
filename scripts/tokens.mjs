// Generates CSS custom properties from the design tokens (light + dark). Run: npm run tokens
import { readFileSync, writeFileSync } from 'node:fs'
const t = JSON.parse(readFileSync(new URL('../src/renderer/tokens.json', import.meta.url)))
const vars = theme => Object.entries(t[theme]).map(([k, v]) => `  --c-${k}: ${v};`).join('\n')
const common = [
  ...Object.entries(t.radius).map(([k, v]) => `  --r-${k}: ${v}px;`),
  ...Object.entries(t.shadow).map(([k, v]) => `  --sh-${k}: ${v};`),
  ...Object.entries(t.motion).map(([k, v]) => `  --m-${k}: ${v};`),
  `  --row-height: ${t.layout['row-height']}px;`, `  --panel-width: ${t.layout['panel-width']}px;`,
  `  --font-sans: ${t.font.sans};`, `  --font-mono: ${t.font.mono};`
].join('\n')
const css = `/* generated by scripts/tokens.mjs */
:root {
${common}
${vars('light')}
  --c-switch-on: #34c759;
  --material-hud: rgba(246, 246, 248, 0.86);
  --material-hud-border: rgba(0, 0, 0, 0.10);
  color-scheme: light;
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${vars('dark')}
    --material-hud: rgba(28, 28, 30, 0.82);
    --material-hud-border: rgba(255, 255, 255, 0.14);
    color-scheme: dark;
  }
}
:root[data-theme="dark"], [data-theme="dark"] {
${vars('dark')}
  --material-hud: rgba(28, 28, 30, 0.82);
  --material-hud-border: rgba(255, 255, 255, 0.14);
  color-scheme: dark;
}
:root[data-theme="light"], [data-theme="light"] {
${vars('light')}
  --material-hud: rgba(246, 246, 248, 0.86);
  --material-hud-border: rgba(0, 0, 0, 0.10);
  color-scheme: light;
}
`
writeFileSync(new URL('../src/renderer/src/tokens.css', import.meta.url), css)
console.log('tokens.css written')
